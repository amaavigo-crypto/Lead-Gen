import type { IncomingMessage, ServerResponse } from 'http';
import fs from 'node:fs';
import path from 'node:path';

type SeoPageModule = {
  renderSeoPage: (template: string, rawPath: string, origin: string) => Promise<string>;
  robotsTxt: (origin: string) => string;
  sitemapXml: (origin: string) => Promise<string>;
  siteOrigin: (headers: Record<string, any>) => string;
};

let modulePromise: Promise<SeoPageModule | null> | null = null;
function loadSeoPageModule(): Promise<SeoPageModule | null> {
  if (!modulePromise) {
    modulePromise = (async () => {
      try {
        // @ts-ignore generated by the production build
        const bundled = await import('./_seo-page.bundle.js');
        if (bundled?.renderSeoPage) return bundled as SeoPageModule;
      } catch (error: any) {
        console.warn('[seo-page] Bundle unavailable; trying source module:', error?.message || error);
      }
      try {
        const source = await import('../src/server/seoPage.js');
        if (source?.renderSeoPage) return source as unknown as SeoPageModule;
      } catch (error: any) {
        console.error('[seo-page] Could not load SEO renderer:', error?.message || error);
      }
      return null;
    })();
  }
  return modulePromise;
}

function trimTrailingSlashes(value: string): string {
  let result = value;
  while (result.endsWith('/')) result = result.slice(0, -1);
  return result;
}
function fallbackOrigin(headers: Record<string, any>): string {
  const configured = trimTrailingSlashes(String(process.env.APP_URL || '').trim());
  if (configured.startsWith('https://') || configured.startsWith('http://')) return configured;
  const host = String(headers['x-forwarded-host'] || headers.host || '').split(',')[0].trim();
  const protocol = String(headers['x-forwarded-proto'] || 'https').split(',')[0].trim();
  return host ? protocol + '://' + host : '';
}

let templateCache: string | null = null;
function loadTemplate(): string {
  if (templateCache) return templateCache;
  for (const relative of ['dist/index.html', 'dist/index.template.html']) {
    try {
      templateCache = fs.readFileSync(path.join(process.cwd(), relative), 'utf8');
      return templateCache;
    } catch { /* try next */ }
  }
  throw new Error('Built dist/index.html is missing');
}

function sendHtml(res: ServerResponse, html: string) {
  res.statusCode = 200;
  res.setHeader('Content-Type', 'text/html; charset=utf-8');
  res.setHeader('Cache-Control', 'public, max-age=0, s-maxage=60, stale-while-revalidate=300');
  res.end(html);
}

export default async function handler(req: IncomingMessage, res: ServerResponse) {
  const url = new URL(req.url || '/', 'http://localhost');
  const site = await loadSeoPageModule();
  const origin = site ? site.siteOrigin(req.headers) : fallbackOrigin(req.headers);
  try {
    const kind = url.searchParams.get('kind');
    if (kind === 'robots') {
      res.setHeader('Content-Type', 'text/plain; charset=utf-8');
      res.setHeader('Cache-Control', 'public, max-age=0, s-maxage=3600');
      return res.end(site ? site.robotsTxt(origin) : 'User-agent: *\nAllow: /\n');
    }
    if (kind === 'sitemap') {
      if (!site) { res.statusCode = 503; return res.end('Sitemap temporarily unavailable'); }
      res.setHeader('Content-Type', 'application/xml; charset=utf-8');
      res.setHeader('Cache-Control', 'public, max-age=0, s-maxage=600, stale-while-revalidate=3600');
      return res.end(await site.sitemapXml(origin));
    }
    const rawPath = url.searchParams.get('p') || '/';
    const template = loadTemplate();
    return sendHtml(res, site ? await site.renderSeoPage(template, rawPath, origin) : template);
  } catch (error: any) {
    console.error('[seo-page] Request failed:', error);
    try { return sendHtml(res, loadTemplate()); }
    catch { res.statusCode = 500; return res.end('Service temporarily unavailable'); }
  }
}
