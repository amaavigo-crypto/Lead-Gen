import type { IncomingMessage, ServerResponse } from 'http';
import fs from 'node:fs';
import path from 'node:path';

type SeoPageModule = {
  renderSeoPage: (template: string, rawPath: string, origin: string) => Promise<string>;
  robotsTxt: (origin: string) => string;
  sitemapXml: (origin: string) => Promise<string>;
  siteOrigin: (headers: Record<string, any>) => string;
};

let seoPageModulePromise: Promise<SeoPageModule | null> | null = null;
let seoHtmlTemplate: string | null = null;

async function loadSeoPageModule(): Promise<SeoPageModule | null> {
  if (!seoPageModulePromise) {
    seoPageModulePromise = (async () => {
      try {
        // @ts-ignore generated by npm run build
        const bundled = await import('./_seo-page.bundle.js');
        if (bundled?.renderSeoPage) return bundled as SeoPageModule;
      } catch (error: any) {
        console.warn('[SEO page] Bundle unavailable; trying source module:', error?.message || error);
      }
      try {
        const source = await import('../src/server/seoPage.js');
        if (source?.renderSeoPage) return source as unknown as SeoPageModule;
      } catch (error: any) {
        console.error('[SEO page] Could not load renderer:', error?.message || error);
      }
      return null;
    })();
  }
  return seoPageModulePromise;
}

function loadSeoHtmlTemplate(): string {
  if (seoHtmlTemplate) return seoHtmlTemplate;
  for (const relative of ['dist/index.html', 'dist/index.template.html']) {
    try {
      seoHtmlTemplate = fs.readFileSync(path.join(process.cwd(), relative), 'utf8');
      return seoHtmlTemplate;
    } catch { /* try the next generated template */ }
  }
  throw new Error('The built public site template is missing from this deployment.');
}

function writeSeoResponse(res: ServerResponse, statusCode: number, contentType: string, body: string, cacheControl: string) {
  res.statusCode = statusCode;
  res.setHeader('Content-Type', contentType);
  res.setHeader('Cache-Control', cacheControl);
  res.end(body);
}

async function handleSeoPageRequest(req: IncomingMessage, res: ServerResponse) {
  try {
    const url = new URL(req.url || '/', 'http://localhost');
    const seo = await loadSeoPageModule();
    const origin = seo
      ? seo.siteOrigin(req.headers as Record<string, any>)
      : (() => {
          const host = String(req.headers['x-forwarded-host'] || req.headers.host || '').split(',')[0].trim();
          const protocol = String(req.headers['x-forwarded-proto'] || 'https').split(',')[0].trim();
          const configured = String(process.env.APP_URL || '').trim().replace(/\/+$/, '');
          return /^https?:\/\//i.test(configured) ? configured : host ? protocol + '://' + host : '';
        })();

    const kind = url.searchParams.get('kind');
    if (kind === 'robots') {
      const body = seo ? seo.robotsTxt(origin) : 'User-agent: *\nAllow: /\n';
      return writeSeoResponse(res, 200, 'text/plain; charset=utf-8', body, 'public, max-age=0, s-maxage=3600');
    }
    if (kind === 'sitemap') {
      if (!seo) return writeSeoResponse(res, 503, 'text/plain; charset=utf-8', 'Sitemap temporarily unavailable', 'no-store');
      const body = await seo.sitemapXml(origin);
      return writeSeoResponse(res, 200, 'application/xml; charset=utf-8', body, 'public, max-age=0, s-maxage=600, stale-while-revalidate=3600');
    }

    const template = loadSeoHtmlTemplate();
    const pagePath = url.searchParams.get('p') || '/';
    const html = seo ? await seo.renderSeoPage(template, pagePath, origin) : template;
    return writeSeoResponse(res, 200, 'text/html; charset=utf-8', html, 'public, max-age=0, s-maxage=60, stale-while-revalidate=300');
  } catch (error: any) {
    console.error('[SEO page] Request failed; serving the base app:', error?.message || error);
    try {
      return writeSeoResponse(res, 200, 'text/html; charset=utf-8', loadSeoHtmlTemplate(), 'public, max-age=0, s-maxage=30');
    } catch {
      res.statusCode = 500;
      return res.end('Service temporarily unavailable');
    }
  }
}


/**
 * Vercel Serverless Catch-All Function for /api/*
 * Bundles all server routes: SMTP/IMAP inbound sync, auto-replies, campaign dispatch, and lead webhooks
 */
export default async function handler(req: IncomingMessage & { body?: any }, res: ServerResponse) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PATCH, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization, X-Google-Access-Token');

  if (req.method === 'OPTIONS') {
    res.statusCode = 204;
    return res.end();
  }

  // Normalize URL in case Vercel rewrote to catch-all query parameter
  if (req.url) {
    try {
      const parsedUrl = new URL(req.url, 'http://localhost');
      if (parsedUrl.pathname.includes('[...path]')) {
        const pathParam = (req as any).query?.path || parsedUrl.searchParams.get('path');
        if (pathParam) {
          const pathStr = Array.isArray(pathParam) ? pathParam.join('/') : pathParam;
          // Keep the original query string (minus Vercel's own `path` param), e.g. ?limit=50&after=...
          const rest = new URLSearchParams(parsedUrl.searchParams);
          rest.delete('path');
          const qs = rest.toString();
          req.url = `/api/${pathStr.replace(/^\/+/, '')}${qs ? `?${qs}` : ''}`;
        }
      }
    } catch {}
  }

  // SEO public routes share this existing catch-all function to stay within Vercel Hobby's function cap.
  if (req.url?.split('?')[0] === '/api/seo-page') {
    return handleSeoPageRequest(req, res);
  }

  if (req.url === '/api/health' || req.url?.startsWith('/api/health?')) {
    res.statusCode = 200;
    res.setHeader('Content-Type', 'application/json');
    return res.end(
      JSON.stringify({
        status: 'healthy',
        service: 'Umrah360 Vercel Serverless Gateway',
        websiteWebhook: {
          endpoint: '/api/webhooks/umrah-demo',
          status: 'ready',
          available: true,
        },
        timestamp: new Date().toISOString(),
      })
    );
  }

  let handleCoreApi: any;
  const loadErrors: string[] = [];
  try {
    // 1. Try bundled server module in /api
    try {
      // @ts-ignore
      const serverMod = await import('./core-server.bundle.js');
      handleCoreApi = serverMod?.handleCoreApi;
    } catch (e: any) {
      loadErrors.push(`bundle: ${e?.message || e}`);
    }

    // 2. Direct fallback to TypeScript source if bundle not present in serverless runtime
    if (!handleCoreApi) {
      try {
        const directMod = await import('../src/server/coreApiHandler.js');
        handleCoreApi = directMod?.handleCoreApi;
      } catch (e: any) {
        loadErrors.push(`source: ${e?.message || e}`);
      }
    }

    if (handleCoreApi) {
      const handled = await handleCoreApi(req, res);
      if (handled) return;
    }
  } catch (err: any) {
    console.error('[API Catch-all] Core API execution error:', err);
    if (!res.writableEnded) {
      res.statusCode = 500;
      res.setHeader('Content-Type', 'application/json');
      return res.end(JSON.stringify({ error: err?.message || 'Internal Server Error' }));
    }
  }

  if (!res.writableEnded) {
    res.setHeader('Content-Type', 'application/json');
    if (!handleCoreApi) {
      // Never pretend success when the API code failed to load.
      console.error('[API Catch-all] Core API handler failed to load:', loadErrors);
      res.statusCode = 500;
      return res.end(JSON.stringify({ error: 'API failed to start', details: loadErrors }));
    }
    res.statusCode = 404;
    res.end(JSON.stringify({ error: 'Not found', url: req.url }));
  }
}